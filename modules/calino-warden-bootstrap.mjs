#!/usr/bin/env node
/**
 * Warden deployment glue for Calino (cal.ts.wyli.tech).
 *
 * Calino is a static, local-first CalDAV client: accounts are either added by
 * hand or preconfigured in calino.config.json, encrypted with a master
 * password the user would otherwise have to type. Warden's radicale is
 * passwordless behind the tailnet (modules/caldav.nix), so there is nothing to
 * protect; this script makes the instance open without a prompt:
 *
 *   config  → writes calino.config.json (before `vite build`)
 *   dist    → writes dist/bootstrap.js and injects it into dist/index.html
 *
 * bootstrap.js seeds `calino.masterPassword`, the key configStore.ts reads to
 * auto-unlock. The payload mirrors encryptPassword() in src/lib/crypto.ts
 * (PBKDF2-SHA256 600k, AES-256-GCM, standard base64) so the app can decrypt it
 * with the fixed app key baked into its bundle.
 *
 * Everything is deterministic: PBKDF2 salts and GCM IVs come from SHA-256 of
 * fixed labels, so a rebuild produces a byte-identical store path instead of
 * churning on every deploy.
 */
import { createHash, webcrypto } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const ITERATIONS = 600_000
const APP_SECRET = 'calino-caldav-v1-2024'
const APP_SALT = 'calino-salt-v1-2024'
const MASTER_KEY = 'calino.masterPassword'

function env(name) {
  const value = process.env[name]
  if (!value) throw new Error(`${name} is required`)
  return value
}

const b64 = (bytes) => Buffer.from(bytes).toString('base64')

function deterministic(label, length) {
  return createHash('sha256').update(label).digest().subarray(0, length)
}

async function deriveKey(password, salt) {
  const material = await webcrypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(password),
    'PBKDF2',
    false,
    ['deriveKey']
  )
  return webcrypto.subtle.deriveKey(
    { name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    material,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt']
  )
}

/** MasterEncryptedData shape ({ciphertext,iv,salt}) used by calino.config.json. */
async function encryptForConfig(plaintext, masterPassword, label) {
  const salt = deterministic(`calino-config-salt|${label}`, 16)
  const iv = deterministic(`calino-config-iv|${label}`, 12)
  const key = await deriveKey(masterPassword, salt)
  const ciphertext = await webcrypto.subtle.encrypt(
    { name: 'AES-GCM', iv },
    key,
    new TextEncoder().encode(plaintext)
  )
  return { ciphertext: b64(ciphertext), iv: b64(iv), salt: b64(salt) }
}

/** EncryptedData shape ({iv,data}) used by encryptPassword() for localStorage. */
async function encryptForStorage(plaintext) {
  const iv = deterministic('calino-app-iv|master-password', 12)
  const key = await deriveKey(APP_SECRET, new TextEncoder().encode(APP_SALT))
  const data = await webcrypto.subtle.encrypt(
    { name: 'AES-GCM', iv },
    key,
    new TextEncoder().encode(plaintext)
  )
  return { iv: b64(iv), data: b64(data) }
}

async function writeConfig() {
  const masterPassword = env('CALINO_MASTER_PASSWORD')
  const [url, username, password] = await Promise.all([
    encryptForConfig(env('CALINO_DAV_URL'), masterPassword, 'url'),
    encryptForConfig(env('CALINO_DAV_USER'), masterPassword, 'username'),
    encryptForConfig(env('CALINO_DAV_PASS'), masterPassword, 'password'),
  ])
  const config = {
    version: 1,
    accounts: [{ name: env('CALINO_ACCOUNT_NAME'), url, username, password }],
    webcalSubscriptions: [],
  }
  writeFileSync(join(ROOT, 'calino.config.json'), JSON.stringify(config, null, 2) + '\n')
  console.log('[calino] wrote calino.config.json')
}

async function patchDist() {
  const dist = join(ROOT, 'dist')
  const masterPassword = env('CALINO_MASTER_PASSWORD')
  const stored = JSON.stringify(await encryptForStorage(masterPassword))
  const bootstrap = `/* generated by scripts/calino-warden-bootstrap.mjs — see header */
;(function () {
  try {
    localStorage.setItem(${JSON.stringify(MASTER_KEY)}, ${JSON.stringify(stored)});
    localStorage.setItem('calino.wardenBootstrap', '1');
  } catch (e) {
    console.error('[calino] could not seed the CalDAV session', e);
  }
})();
`
  writeFileSync(join(dist, 'bootstrap.js'), bootstrap)

  const indexPath = join(dist, 'index.html')
  const html = readFileSync(indexPath, 'utf8')
  const tag = '<script src="/bootstrap.js"></script>'
  if (html.includes(tag)) return
  // Must run before the app bundle: a classic script in <head> executes while
  // parsing, module scripts are deferred.
  const patched = html.replace('</head>', `  ${tag}\n  </head>`)
  if (patched === html) throw new Error('dist/index.html has no </head> to inject into')
  writeFileSync(indexPath, patched)
  console.log('[calino] injected dist/bootstrap.js')
}

const mode = process.argv[2]
if (mode === 'config') await writeConfig()
else if (mode === 'dist') await patchDist()
else throw new Error('usage: calino-warden-bootstrap.mjs config|dist')
